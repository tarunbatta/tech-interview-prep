// Url: https://leetcode.com/problems/generalized-abbreviation

/*
320. Generalized Abbreviation
Medium

A word's generalized abbreviation can be generated by replacing any number of non-adjacent substrings with their lengths.

For example, a string such as "word" can be abbreviated to:
- "4" ("word" -> "4")
- "3d" ("wor" -> "3")
- "w2d" ("or" -> "2")
- "word" (no substrings replaced)

Given a string word, return a list of all the possible generalized abbreviations of word. Return the answer in any order.

Example 1:
Input: word = "word"
Output: ["4","3d","2r1","2rd","1o2","1o1d","1or1","1ord","w3","w2d","w1r1","w1rd","wo2","wo1d","wor1","word"]

Example 2:
Input: word = "a"
Output: ["1","a"]

Constraints:
1 <= word.length <= 15
word consists of only lowercase English letters.
*/

using System;
using System.Collections.Generic;
using System.Text;

namespace InterviewPreperationGuide.Core.LeetCode.problem320
{
    public class Solution
    {
        public void Init()
        {
            var res = GenerateAbbreviations("word");
            Console.WriteLine(string.Join(", ", res));

            var res2 = GenerateAbbreviations("a");
            Console.WriteLine(string.Join(", ", res2)); // 1, a
        }

        // Time: O(n * 2^n) where n is word.Length (2^n combinations, each takes O(n) to construct)
        // Space: O(n) for recursion stack and current StringBuilder
        public static IList<string> GenerateAbbreviations(string word)
        {
            List<string> result = new();
            word ??= string.Empty;

            Backtrack(word, 0, new StringBuilder(), 0, result);
            return result;
        }

        private static void Backtrack(string word, int index, StringBuilder sb, int count, List<string> result)
        {
            int originalLen = sb.Length;

            if (index == word.Length)
            {
                if (count > 0)
                {
                    sb.Append(count);
                }

                result.Add(sb.ToString());
                sb.Length = originalLen;
                return;
            }

            // Option 1: Abbreviate current character (increment count)
            Backtrack(word, index + 1, sb, count + 1, result);

            // Option 2: Keep current character (flush count if any, append word[index])
            if (count > 0)
            {
                sb.Append(count);
            }
            sb.Append(word[index]);

            Backtrack(word, index + 1, sb, 0, result);

            sb.Length = originalLen;
        }
    }
}